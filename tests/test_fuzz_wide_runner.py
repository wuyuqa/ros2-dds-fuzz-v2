def reference_json_hash(value):
    """Independent canonical JSON/SHA; never calls production hash helpers."""
    return hashlib.sha256(json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
        allow_nan=False).encode("utf-8")).hexdigest()


def reference_generation(surface_id, rmw, *, content_v2):
    value = copy.deepcopy(_HISTORICAL_CYCLONE_ROWS[surface_id])
    updates = []
    if rmw == FASTRTPS:
        updates.append(_HISTORICAL_FAST_UPDATES[surface_id])
    if content_v2:
        updates.append(_CONTENT_V2_UPDATES[(surface_id, rmw)])
    for update in updates:
        for path, replacement in update.items():
            parent = value
            for key in path[:-1]:
                parent = parent[key]
            parent[path[-1]] = copy.deepcopy(replacement)
    return value


def reference_child_content(row, *, content_v2):
    """Independent projection for these three single-operation fixture schemas.

    Deliberately not a general replacement for corpus.content_identity.  Literal
    preimages above retain all operation/receipt/RNG fields for full replay;
    only this semantic-content projection removes generation provenance.
    """
    plan = row["mutation_plan"]
    identity = {"target_id": row["target_id"], "target_revision": 0,
                "rmw": row["rmw"], "contract_hash": plan["contract_hash"],
                "final_config": copy.deepcopy(row["final_input"]),
                "runtime_windows": copy.deepcopy(plan["runtime_windows"])}
    if content_v2:
        operations = []
        for original in plan["operations"]:
            operation = {key: copy.deepcopy(original[key]) for key in (
                "schema", "surface_id", "mutator_id", "parameters",
                "application_phase", "applicability_result")}
            if operation["application_phase"] == "compile_time":
                operation["parameters"].pop("boundary_class", None)
            operations.append(operation)
        identity["operations"] = operations
        schema = "r2f.corpus-content/v2"
    else:
        identity["operations"] = copy.deepcopy(plan["operations"])
        identity["mutation_plan"] = copy.deepcopy(plan)
        identity["mutation_plan"].pop("rng_seed")
        schema = "r2f.s1-corpus/v1"
    return reference_json_hash({"schema": schema, "identity": identity})


