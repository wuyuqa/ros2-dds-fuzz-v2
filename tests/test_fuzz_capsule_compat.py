SOURCE = {"source_repo": "/home/wuyuqa/ros2-dds-fuzz-v2", "head": "offline-head",
          "behavior_tree_sha256": "a" * 64, "source_frozen": True, "dirty_behavior_paths": []}

EXPLORATORY_TARGET = "discovery.late_endpoint.fuzz_v1"
BASE_LATE = {
    "topic": "/r2f/s1/late_endpoint", "message_type": "std_msgs/msg/String",
    "qos": {"reliability": "reliable", "durability": "volatile", "depth": 64},
    "reader_delay_sec": 0.15, "baseline_reader_delay_sec": 0.02,
    "pre_match_count": 2, "post_match_count": 6, "publish_interval_sec": 0.03,
}
WINDOWS = [{"schema": "r2f.runtime-window/v1", "window_id": "w1", "window_index": 0,
            "trigger_anchor": "fresh_match", "trigger_offset_sec": 0.0,
            "drop_duration_sec": 0.2, "restore_interval_sec": 0.1}]


def legacy_scenario():
    return compile_scenario(legacy_target(), "rmw_cyclonedds_cpp", "mutated", 0, seed=7)


def legacy_submitted():
    return {"topic": "/r2f/conformance", "message_type": "std_msgs/msg/String",
            "qos": {"reliability": "reliable"}}


def plan_scenario(*, seed=7, windows=None):
    """Offline exploratory scenario whose plan was generated by real mutators."""
    targets = exploratory_target_declarations()
    provider = S1ExploratoryMutationProvider(targets)
    contract = provider.contract_for(EXPLORATORY_TARGET)
    proposal = mutate(BASE_LATE, contract.surface_by_id["P01"], make_rng(seed), mutator_id="M03")
    plan = compose(BASE_LATE, [proposal], contract, rng_seed=seed,
                   runtime_windows=windows)
    target = targets[EXPLORATORY_TARGET]
    scenario = compile_scenario(
        target, "rmw_cyclonedds_cpp", "mutated", 0, seed,
        {"mutation_kind": target.mutation_slots[0].mutation_kind,
         "carrier": target.mutation_slots[0].carrier},
        mutation_plan=plan)
    return scenario, plan


class LegacyCapsuleCompatibility(unittest.TestCase):
    def test_v1_capsule_roundtrip_and_hash_are_unchanged(self):
        scenario = legacy_scenario()
        capsule = ReplayCapsule.from_scenario(scenario, source_manifest=SOURCE,
                                              final_input=legacy_submitted(), origin_domain=51)
        data = capsule.to_dict()
        self.assertEqual(data["schema"], CAPSULE_SCHEMA)
        self.assertEqual(data["input"]["input_identity_schema"], INPUT_SCHEMA)
        self.assertNotIn("mutation_plan", data["input"])
        # Independent recomputation of the frozen v1 whitelist digest.
        keys = ("target_id", "target_revision", "target_sha256", "mutation_kind", "carrier",
                "mutation_parameters", "rmw", "repeat", "seed", "arm", "mutation_layer_order",
                "input_layer_receipts", "final_input", "state_steps", "source_manifest")
        body = {"schema": INPUT_SCHEMA,
                **{key: data["input"]["effective_input"][key] for key in keys
                   if key in data["input"]["effective_input"]}}
        encoded = json.dumps(body, sort_keys=True, separators=(",", ":"),
                             ensure_ascii=False, allow_nan=False).encode("utf-8")
        expected = hashlib.sha256(encoded).hexdigest()
        self.assertEqual(data["input"]["effective_input_sha256"], expected)
        self.assertEqual(effective_input_hash(data["input"]["effective_input"]), expected)
        self.assertTrue(validate_replay_input(data["input"]))
        self.assertEqual(ReplayCapsule.from_dict(json.loads(json.dumps(data))).to_dict(), data)

    def test_v1_rejects_v2_fields_instead_of_silently_ignoring_them(self):
        capsule = ReplayCapsule.from_scenario(legacy_scenario(), source_manifest=SOURCE,
                                              final_input=legacy_submitted())
        _, plan = plan_scenario()
        for field, value in (("mutation_plan", plan.to_dict()),
                             ("operations", [op.to_dict() for op in plan.operations]),
                             ("runtime_windows", WINDOWS),
                             ("contract_hash", plan.contract_hash)):
            tampered = copy.deepcopy(capsule.to_dict()["input"])
            tampered[field] = copy.deepcopy(value)
            with self.subTest(field=field), self.assertRaises(ValueError):
                validate_replay_input(tampered)
            effective_tampered = copy.deepcopy(capsule.to_dict()["input"])
            effective_tampered["effective_input"][field] = copy.deepcopy(value)
            with self.subTest(field="effective." + field), self.assertRaises(ValueError):
                validate_replay_input(effective_tampered)


class PlanCapsuleV2(unittest.TestCase):
    def test_v2_plan_capsule_roundtrip_and_hash_binds_plan_fields(self):
        scenario, plan = plan_scenario()
        capsule = ReplayCapsule.from_scenario(scenario, source_manifest=SOURCE)
        data = capsule.to_dict()["input"]
        self.assertEqual(data["input_identity_schema"], INPUT_SCHEMA_V2)
        self.assertEqual(data["effective_input"]["input_identity_schema"], INPUT_SCHEMA_V2)
        for key in ("mutation_plan", "operations", "runtime_windows", "contract_hash"):
            self.assertIn(key, data)
            self.assertEqual(data[key], data["effective_input"][key])
        self.assertTrue(validate_replay_input(data))
        self.assertEqual(ReplayCapsule.from_dict(capsule.to_dict()).to_dict(), capsule.to_dict())

    def test_v2_hash_changes_with_plan_operations_windows_and_final_input(self):
        scenario, plan = plan_scenario(windows=WINDOWS)
        capsule = ReplayCapsule.from_scenario(scenario, source_manifest=SOURCE)
        base = capsule.input
        base_digest = base["effective_input_sha256"]
        variants = {
            "mutation_plan": dict(base, mutation_plan=dict(
                plan.to_dict(), rng_seed=plan.rng_seed + 1)),
            "operations": dict(base, operations=[
                dict(op.to_dict(), op_id=op.op_id + "-other") for op in plan.operations]),
            "runtime_windows": dict(base, runtime_windows=[
                dict(WINDOWS[0], drop_duration_sec=0.5)]),
            "contract_hash": dict(base, contract_hash="b" * 64),
            "final_input": dict(base["effective_input"],
                                final_input=dict(base["effective_input"]["final_input"],
                                                 reader_delay_sec=0.9)),
        }
        for field, changed in variants.items():
            with self.subTest(field=field):
                if field == "final_input":
                    digest = effective_input_hash(changed, schema=INPUT_SCHEMA_V2)
                elif field == "mutation_plan":
                    effective = dict(base["effective_input"],
                                     mutation_plan=changed["mutation_plan"])
                    digest = effective_input_hash(effective, schema=INPUT_SCHEMA_V2)
                else:
                    effective = dict(base["effective_input"], **{field: changed[field]})
                    digest = effective_input_hash(effective, schema=INPUT_SCHEMA_V2)
                self.assertNotEqual(digest, base_digest, field)

    def test_v2_rejects_tampered_plan_final_input_or_source(self):
        scenario, plan = plan_scenario()
        capsule = ReplayCapsule.from_scenario(scenario, source_manifest=SOURCE)
        original = capsule.input

        tampered_plan = copy.deepcopy(original)
        tampered_plan["effective_input"]["mutation_plan"] = dict(
            plan.to_dict(), rng_seed=plan.rng_seed + 5)
        tampered_plan["mutation_plan"] = tampered_plan["effective_input"]["mutation_plan"]
        # Recompute so only the cross-binding is wrong, not the digest.
        tampered_plan["effective_input_sha256"] = effective_input_hash(
            tampered_plan["effective_input"], schema=INPUT_SCHEMA_V2)
        with self.assertRaises(ValueError):
            validate_replay_input(tampered_plan)

        tampered_input = copy.deepcopy(original)
        tampered_input["effective_input"]["final_input"] = dict(
            original["effective_input"]["final_input"], reader_delay_sec=2.5)
        tampered_input["effective_input_sha256"] = effective_input_hash(
            tampered_input["effective_input"], schema=INPUT_SCHEMA_V2)
        with self.assertRaises(ValueError):
            validate_replay_input(tampered_input)

        # Source authenticity is ultimately checked at replay time against the
        # current frozen source; inside the capsule the manifest must at least
        # agree with the effective-input binding and its digest.
        tampered_source = copy.deepcopy(original)
        tampered_source["source_manifest"] = dict(SOURCE, head="another-head")
        with self.assertRaises(ValueError):
            validate_replay_input(tampered_source)
        tampered_source = copy.deepcopy(original)
        tampered_source["effective_input"]["source_manifest"] = dict(SOURCE, head="another-head")
        with self.assertRaises(ValueError):
            validate_replay_input(tampered_source)

    def test_v2_rejects_unknown_schema_and_missing_plan_fields(self):
        scenario, _ = plan_scenario()
        capsule = ReplayCapsule.from_scenario(scenario, source_manifest=SOURCE)
        for schema in ("r2f.input-identity/v9", "", None):
            bad = copy.deepcopy(capsule.input)
            bad["input_identity_schema"] = schema
            with self.subTest(schema=schema), self.assertRaises(ValueError):
                validate_replay_input(bad)
        for key in ("mutation_plan", "operations", "runtime_windows", "contract_hash"):
            bad = copy.deepcopy(capsule.input)
            bad["effective_input"].pop(key)
            bad.pop(key, None)
            with self.subTest(missing=key), self.assertRaises(ValueError):
                validate_replay_input(bad)

    def test_v2_replay_requires_plan_aware_opt_in_not_a_silent_v1_fallback(self):
        from r2f.core.replay import rerun_conformance
        scenario, _ = plan_scenario()
        capsule = ReplayCapsule.from_scenario(scenario, source_manifest=SOURCE, origin_domain=51)
        original_input = copy.deepcopy(capsule.input)
        calls = []

        def runner(s, domain):
            calls.append(domain)
            raise AssertionError("v1 replay path must not run a v2 capsule")

        result = rerun_conformance(capsule, runner, domain=52)
        self.assertEqual(result["status"], "fail_artifact")
        self.assertEqual(result["reason_code"], "v2_plan_aware_runner_required")
        self.assertEqual(calls, [])
        # The saved plan/input is retained byte-identically; nothing is regenerated.
        self.assertEqual(capsule.input, original_input)
        self.assertEqual(capsule.to_dict()["input"], json.loads(json.dumps(capsule.input)))
        restored = ReplayCapsule.from_dict(capsule.to_dict())
        self.assertTrue(validate_replay_input(restored.input))

    def test_v2_loading_never_calls_a_mutator_or_provider(self):
        scenario, _ = plan_scenario()
        capsule = ReplayCapsule.from_scenario(scenario, source_manifest=SOURCE)
        payload = json.loads(json.dumps(capsule.to_dict()))
        with patch("r2f.core.mutators.mutate", side_effect=AssertionError("mutator called")), \
             patch.object(S1ExploratoryMutationProvider, "prepare",
                          side_effect=AssertionError("prepare called")), \
             patch.object(S1ExploratoryMutationProvider, "prepare_plan",
                          side_effect=AssertionError("prepare_plan called")):
            loaded = ReplayCapsule.from_dict(payload)
            self.assertTrue(validate_replay_input(loaded.input))
        self.assertEqual(loaded.to_dict(), capsule.to_dict())


if __name__ == "__main__":
    unittest.main()
