_BOUNDARIES = {"topology_state_boundary", "state_step_before", "state_step_after",
               "topology_pair_observation"}


def _save(directory, name, value):
    (directory / (name + ".json")).write_text(
        json.dumps(value, sort_keys=True, indent=2, allow_nan=False) + "\n")


def _program(*, generations=False):
    program = model.generate_program(7, writers=2, readers=2)
    for endpoint in program["endpoints"]:
        endpoint["topic"] = "/r2f/integration/shared"
        endpoint["qos"].update(reliability="reliable", durability="volatile")
    if generations:
        # Authored INPUT lifecycle, not an observation or a forged raw proof.
        program["actions"][-1:-1] = [
            {"action_id": "destroy_w0_g1", "op": "destroy", "endpoint_id": "w0",
             "generation": 1, "params": {}, "depends_on": []},
            {"action_id": "recreate_w0_g2", "op": "recreate", "endpoint_id": "w0",
             "generation": 2, "params": {}, "depends_on": []},
            {"action_id": "publish_w0_g2", "op": "publish_batch", "endpoint_id": "w0",
             "generation": 2, "params": {"count": 2, "start_sequence": 0,
                                         "interval_sec": 0.01, "payload": "generation-two"},
             "depends_on": []},
        ]
    assert model.validate_program(program)["status"] == "valid"
    return program


def _route_config(program, name):
    # Use the production plan/Scenario identity path, not copied raw lineage.
    plan = make_topology_plan(program, [{"operator_id": "action.insert"}], rng_seed=7)
    scenario = Scenario(topology_target_declaration(), "rmw_cyclonedds_cpp",
                        "mutated", 0, seed=7, mutation_plan=plan)
    effective = scenario.effective_input_v2(
        final_input=plan.final_config,
        input_layer_receipts=topology_input_layer_receipts(plan),
        source_manifest={"head": None, "source_frozen": False})
    return {**deepcopy(effective), "effective_input": effective,
            "effective_input_sha256": effective_input_hash(effective, schema=INPUT_SCHEMA_V2),
            "plan_hash": plan.plan_hash(), "topology_program": deepcopy(plan.final_config["topology_program"]),
            "runtime_capability": TOPOLOGY_CAPABILITY, "backend": "offline_fake",
            "domain_id": 191, "run_id": "i3-integration-offline-" + name}


def _consume(program, config, runtime, directory):
    assert runtime["status"] == "executed", runtime.get("reason")
    raw = Path(runtime["raw_path"])
    persisted = [json.loads(line) for line in raw.read_text().splitlines()]
    boundaries = [e for e in persisted if e["event"] == "topology_state_boundary"]
    if len(boundaries) < 2:
        boundaries = [e for e in persisted if e["event"] in _BOUNDARIES]
    assert len(boundaries) >= 2
    projection = project_topology_state(
        program, raw, before_ref=boundaries[0]["event_index"],
        after_ref=boundaries[-1]["event_index"], expected_sha256=runtime["raw_sha256"])
    producer = TopologyFactProducer().produce(
        {"events": runtime["events"], "runtime": runtime, "config": config})
    for name, value in (("program", program), ("config", config), ("runtime", runtime),
                        ("projection", projection), ("producer", producer)):
        _save(directory, name, value)
    _save(directory, "event-inventory", dict(Counter(e["event"] for e in persisted)))
    return {"program": program, "config": config, "runtime": runtime,
            "events": persisted, "projection": projection, "producer": producer,
            "directory": directory}


@pytest.fixture(scope="module", params=["multiwriter", "generations", "no_delivery", "no_match"])
def episode(request, tmp_path_factory):
    directory = tmp_path_factory.mktemp("runtime-projection-" + request.param)
    backend = OfflineTopologyBackend(auto_delivery=request.param != "no_delivery",
                                     auto_match=request.param != "no_match")
    config = _route_config(_program(generations=request.param == "generations"), request.param)
    runtime = run_topology_route(config, directory, backend=backend)
    return _consume(config["topology_program"], config, runtime, directory)


def test_runtime_persisted_raw_equals_returned_events(episode):
    runtime, events = episode["runtime"], episode["events"]
    assert events == runtime["events"], "runtime mutated an already serialized raw row"
    assert runtime["raw_sha256"] == hashlib.sha256(Path(runtime["raw_path"]).read_bytes()).hexdigest()
    assert [e["event_index"] for e in events] == list(range(len(events)))
    assert all(e["backend"] == "offline_fake" for e in events)


