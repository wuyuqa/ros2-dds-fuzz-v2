def test_before_after_refs_are_raw_bounded_and_chronological(episode):
    receipt = episode["projection"]["receipt"]
    assert receipt["status"] != "invalid", receipt["reasons"]
    assert receipt["chronology"]["status"] == "verified"
    before, after = (receipt[side]["boundary_ref"] for side in ("before", "after"))
    assert before["event_index"] < after["event_index"]
    for side in ("before", "after"):
        boundary = receipt[side]["boundary_ref"]
        for component in receipt[side]["component_refs"].values():
            for ref in component["refs"]:
                assert (ref["path"], ref["sha256"]) == (boundary["path"], boundary["sha256"])
                assert ref["event_index"] <= boundary["event_index"]


def test_missing_raw_proof_stays_unknown_not_config_or_helper_labels(episode):
    projection, events = episode["projection"], episode["events"]
    if not any(e["event"] == "topology_network_observation" for e in events):
        assert projection["state_after"]["network_phase"] == "unknown"
        assert projection["state_after"]["recovery_cycle_bucket"] == "unknown"
    if not any(e["event"] == "topology_delivery_window_closed" for e in events):
        assert all(p["delivery_closure"] == "unknown" for p in projection["state_after"]["pairs"])
    if not any(e["event"] == "topology_controlled_isolation" or
               e.get("peer_proof_source") == "dds_matched_endpoint_api" for e in events):
        assert all(p["observed_match"] == "unknown" for p in projection["state_after"]["pairs"])
    # Completeness flags alone may never erase those missing observations.
    if any(p["observed_match"] == "unknown" or p["delivery_closure"] == "unknown"
           for p in projection["state_after"]["pairs"]):
        assert projection["state_after"]["observation_completeness"] == "incomplete"


