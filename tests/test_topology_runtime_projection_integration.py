def test_unique_actual_payload_send_chains_remain_per_writer_generation(episode):
    events = episode["events"]
    sends = [e for e in events if e["event"] == "send"]
    receives = [e for e in events if e["event"] == "receive"]
    if episode["config"]["run_id"].endswith(("no_delivery", "no_match")):
        assert sends and not receives
        return
    assert receives and {e["payload_writer_id"] for e in receives} == {"w0", "w1"}
    for receive in receives:
        candidates = [s for s in sends if s["payload_sha256"] == receive["payload_sha256"]
                      and s["run_id"] == receive["payload_run_id"]
                      and s["logical_id"] == receive["payload_writer_id"]
                      and s["generation"] == receive["payload_writer_generation"]
                      and s["send_sequence"] == receive["send_sequence"]]
        assert len(candidates) == 1
        sent = candidates[0]
        for row in (sent, receive):
            creations = [e for e in events if e["event"] == "endpoint_created"
                         and all(e.get(k) == row.get(k) for k in
                                 ("logical_id", "generation", "endpoint_gid", "pid",
                                  "process_start_ticks", "endpoint_generation"))]
            assert len(creations) == 1
            assert creations[0]["event_index"] < row["event_index"]
    # Same seq in two writers is valid; there is no cross-writer total order gate.
    assert any(a["send_sequence"] == b["send_sequence"] and a["logical_id"] != b["logical_id"]
               for a in sends for b in sends)


def test_repeated_generation_has_fresh_identity_and_no_inherited_payload(tmp_path):
    program = _program(generations=True)
    config = {"backend": "offline_fake", "run_id": "i3-generation-direct", "domain_id": 191}
    result = run_topology(program, config, tmp_path, backend=OfflineTopologyBackend())
    episode = _consume(program, config, result, tmp_path)
    events = episode["events"]
    created = [e for e in events if e["event"] == "endpoint_created" and e["logical_id"] == "w0"]
    retired = [e for e in events if e["event"] in ("endpoint_destroyed", "topology_endpoint_destroyed")
               and e.get("logical_id") == "w0"]
    assert [e["generation"] for e in created] == [1, 2]
    assert len(retired) == 1
    assert created[0]["event_index"] < retired[0]["event_index"] < created[1]["event_index"]
    assert len({e["endpoint_gid"] for e in created}) == 2
    assert len({(e["pid"], e["process_start_ticks"], e["endpoint_generation"]) for e in created}) == 2
    for generation in (1, 2):
        sent = [e for e in events if e["event"] == "send" and e.get("logical_id") == "w0"
                and e.get("generation") == generation]
        assert sent[0]["send_sequence"] == 0  # legal repetition across generations
        assert all(e["endpoint_gid"] == created[generation - 1]["endpoint_gid"] for e in sent)
    assert events == result["events"]


def test_count_one_2w2r_ambiguity_requires_actual_runtime_inventory(tmp_path):
    """Acceptance probe: do not silently substitute a handmade counterexample.

    Current OfflineTopologyBackend filters graph by its match map, and has no
    independent graph-visibility/count knobs. This remains RED until production
    backend can really emit the requested ambiguous observation fixture.
    """
    program = _program()
    config = {"backend": "offline_fake", "run_id": "i3-ambiguity-direct", "domain_id": 191}
    runtime = run_topology(program, config, tmp_path, backend=OfflineTopologyBackend(match_policy="one_to_one", graph_visibility="all_live_topic", publisher_gid_available=True))
    episode = _consume(program, config, runtime, tmp_path)
    events = episode["events"]
    witnesses = []
    for graph in (e for e in events if e["event"] == "graph_snapshot"):
        counts = [e for e in events if e["event"] == "match_snapshot"
                  and all(e.get(k) == graph.get(k) for k in ("logical_id", "generation", "command_id"))]
        if len(graph["publishers"]) == len(graph["subscriptions"]) == 2 and len(counts) == 1:
            if counts[0]["matched_count"] == 1:
                witnesses.append(graph)
    assert {e["logical_id"] for e in witnesses} == {"w0", "w1", "r0", "r1"}, (
        "HARNESS_GAP: actual offline runtime did not emit full 2W2R visible inventory + counts1; "
        "no authored raw substituted; see persisted event-inventory.json")
    assert all(p["observed_match"] == "unknown" for p in episode["projection"]["state_after"]["pairs"])


def test_no_gid_payload_basis_requires_actual_backend_receive(tmp_path):
    """Positive attribution checkpoint; never remove GIDs from returned raw."""
    program = _program()
    config = {"backend": "offline_fake", "run_id": "i3-payload-direct", "domain_id": 191}
    runtime = run_topology(program, config, tmp_path, backend=OfflineTopologyBackend(match_policy="all", publisher_gid_available=False))
    episode = _consume(program, config, runtime, tmp_path)
    receives = [e for e in episode["events"] if e["event"] == "receive" and not e.get("publisher_gid")]
    assert receives, ("HARNESS_GAP: OfflineTopologyBackend auto-delivery always emits publisher_gid; "
                      "endpoint_correlated_payload branch not exercised; no raw field removed")
    for receive in receives:
        pairs = [p for p in runtime["pair_facts"] if p["writer"] == receive.get("payload_writer_id")
                 and p["reader"] == receive.get("logical_id")]
        assert len(pairs) == 1
        witness, reason = payload_delivery_witness(pairs[0], receive, episode["events"])
        assert reason is None, reason
        assert witness["identity_basis"] == "endpoint_correlated_payload"
        assert witness["direct_gid_match"] is None


def test_duplicate_create_generation_is_guarded_without_duplicate_raw_identity(tmp_path):
    program = _program()
    first = next(a for a in program["actions"] if a["op"] == "create" and a["endpoint_id"] == "w0")
    repeated = deepcopy(first)
    repeated["action_id"] = "duplicate_w0_generation_one"
    index = program["actions"].index(first)
    program["actions"].insert(index + 1, repeated)
    assert model.validate_program(program)["status"] == "valid"
    config = {"backend": "offline_fake", "run_id": "i3-duplicate-generation", "domain_id": 191}
    runtime = run_topology(program, config, tmp_path, backend=OfflineTopologyBackend())
    episode = _consume(program, config, runtime, tmp_path)
    created = [e for e in episode["events"] if e["event"] == "endpoint_created"
               and e.get("logical_id") == "w0" and e.get("generation") == 1]
    assert len(created) == 1
    guards = [e for e in episode["events"] if e["event"] == "topology_guard_reject"
              and e.get("step_id") == "action:duplicate_w0_generation_one"]
    assert len(guards) == 1 and guards[0]["no_side_effect"] is True
    assert not episode["projection"]["eligible"]
    assert episode["events"] == runtime["events"]
